#include <iostream>
using namespace std;

int main() {
    float a, b;
    
    cout << "Input dua bilangan: ";
    cin >> a >> b;

    cout << "Tambah = " << a + b << endl;
    cout << "Kurang = " << a - b << endl;
    cout << "Kali = " << a * b << endl;
    cout << "Bagi = " << a / b << endl;

    return 0;
}